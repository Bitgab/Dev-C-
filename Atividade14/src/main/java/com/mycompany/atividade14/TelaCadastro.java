    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        // TODO add your handling code here:
        String buscarNome = txtBuscar.getText().trim();
        
        if (buscarNome.isEmpty()){
            JOptionPane.showMessageDialog(null, "Digite um nome para buscar");
            return;
        }
        boolean encontrado = false;
        for (Pessoa pessoa: listaPessoa) {
            if (pessoa.getNome().equalsIgnoreCase(buscarNome)){
                txtNome.setText(pessoa.getNome());
                txtIdade.setText(String.valueOf(pessoa.getIdade()));
                encontrado = true;
                break;
            }
        }
        
        if (!encontrado){
            JOptionPane.showMessageDialog(null, "Pessoa não encontrada.");
        }
        
    }//GEN-LAST:event_btnBuscarActionPerformed

