    private void btnRemoverPessoaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRemoverPessoaActionPerformed
        // TODO add your handling code here:
   String nomeBusca = txtBuscar.getText().trim();
   if (nomeBusca.isEmpty()) {
       JOptionPane.showMessageDialog(null, "Digite um nome para remover");
       return;
   }
   
   boolean removido = false;
   
   for (int i = 0; i < listaPessoa.size(); i++) {
       if (listaPessoa.get(i).getNome().equalsIgnoreCase(nomeBusca)) {
           listaPessoa.remove(i);
           removido = true;
           break;
       }
   }
   
   if (removido){
       JOptionPane.showMessageDialog(null, "Pessoa removida com sucesso!");
   } else {
       JOptionPane.showMessageDialog(null, "Pessoa não encontrada.");
   }
        
    }//GEN-LAST:event_btnRemoverPessoaActionPerformed

